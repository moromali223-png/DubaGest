/// Sérialisation JSON <-> Entités Microfinance (alignée sur les colonnes PostgreSQL).
abstract final class MicrofinanceMappers {
  static DateTime? _dt(Object? v) {
    if (v == null) return null;
    if (v is DateTime) return v;
    if (v is String && v.isNotEmpty) return DateTime.tryParse(v);
    return null;
  }

  static int _i(Object? v, [int fallback = 0]) => (v as num?)?.toInt() ?? fallback;
  static double _d(Object? v, [double fallback = 0]) => (v as num?)?.toDouble() ?? fallback;

  // --- ACCOUNTS ---

  static MicrofinanceAccount accountFromJson(Map<String, dynamic> j) => MicrofinanceAccount(
        id: j['id'] as String,
        entrepriseId: j['entreprise_id'] as String,
        perimetreId: j['perimetre_id'] as String?,
        nom: j['nom'] as String? ?? 'Caisse Microfinance',
        typeCompte: TypeCompteMicrofinance.parse(j['type_compte'] as String?),
        sourceFondsDefaut: SourceFondsMicrofinance.parse(j['source_fonds_defaut'] as String?),
        caisseId: j['caisse_id'] as String?,
        numeroCompte: j['numero_compte'] as String?,
        soldeInitial: _i(j['solde_initial']),
        soldeActuel: _i(j['solde_actuel']),
        devise: j['devise'] as String? ?? 'XOF',
        estActif: j['est_actif'] as bool? ?? true,
        observations: j['observations'] as String?,
        creePar: j['cree_par'] as String?,
        version: _i(j['version'], 1),
        createdAt: _dt(j['created_at']) ?? DateTime.now(),
        updatedAt: _dt(j['updated_at']) ?? DateTime.now(),
        deletedAt: _dt(j['deleted_at']),
      );

  static Map<String, dynamic> accountToJson(MicrofinanceAccount a) => {
        'id': a.id,
        'entreprise_id': a.entrepriseId,
        if (a.perimetreId != null) 'perimetre_id': a.perimetreId,
        'nom': a.nom,
        'type_compte': a.typeCompte.code,
        'source_fonds_defaut': a.sourceFondsDefaut.code,
        if (a.caisseId != null) 'caisse_id': a.caisseId,
        if (a.numeroCompte != null) 'numero_compte': a.numeroCompte,
