        if (a.creePar != null) 'cree_par': a.creePar,
        'version': a.version,
        'created_at': a.createdAt.toUtc().toIso8601String(),
        'updated_at': a.updatedAt.toUtc().toIso8601String(),
        if (a.deletedAt != null) 'deleted_at': a.deletedAt!.toUtc().toIso8601String(),
